-- Practice:02 ->RIGHT OUTER JOIN Display all departments, even those that have no employees.
SELECT d.DeptName
FROM EMPLOYEE e 
RIGHT OUTER JOIN DEPARTMENT d 
    ON e.DeptID = d.DeptID;
	
-- Practice:03 ->FULL OUTER JOIN Display all students and all course registrations, including unmatched records from either table.
SELECT s.Name , r.CourseID
FROM STUDENT s 
FULL OUTER JOIN REGISTRATION r 
    ON s.StudentID = r.StudentID;
	
Join	          Keep all rows from	     Unmatched rows
LEFT OUTER JOIN	  Left table	             Right-side columns become NULL
RIGHT OUTER JOIN  Right table	             Left-side columns become NULL
FULL OUTER JOIN	  Both tables	             Missing-side columns become NULL